"""Write the across-seed noise record for one submission: gate G1's measurement.

Each verifier derives its simulator seed from the candidate's own bytes, so a re-run at the
default salt is bit-identical and measures nothing. Passing an explicit `--seed` overrides
that derivation, which is the only way to see how much of a cost difference is the draw
rather than the circuit. This records one unchanged submission re-verified under several
seeds, so a later candidate's gain can be compared against the noise it has to clear.

Only measurements go in the file. Every aggregate the artifact page and the README quote --
the per-task spread, the failure count, the confidence interval on it -- is recomputed from
these rows at render time, so the two can never disagree.

    uv run --extra tracking python scripts/build_seed_record.py \\
        <rows-dir> --submission-ref 57834335 --shots-per-run 102400
"""

from __future__ import annotations

from pathlib import Path
from typing import Annotated, Any

import typer
import yaml

from quantum_compilation.cost import TASKS
from quantum_compilation.verify import VerificationRun

PROJECT_ROOT = Path(__file__).resolve().parents[1]
EXPERIMENTS_DIR = PROJECT_ROOT / "docs" / "experiments"

HEADER = """\
# Gate G1: one unchanged submission re-verified under several explicit verifier seeds, to size
# how much of a cost difference is the simulator's draw rather than the circuit. Generated by
# scripts/build_seed_record.py from the per-seed rows.jsonl our own verifier runs wrote; do not
# hand-edit.
#
# Measurements only. The per-task spread, the failed-shot count and the confidence interval on
# it are all recomputed from these rows wherever they are quoted, so no aggregate here can fall
# out of step with the rows it came from.
#
# `dqi_detail` is the dqi verifier's own reported fields, copied verbatim. `empirical_error_rate`
# times `shots_per_run` is the number of shots its decoder failed, which is the whole of that
# task's variance: the rate is 0 or one failure, never a continuum.
"""

# The dqi report fields that drive its cost, in the order the verifier derives them.
DQI_DETAIL = (
    "empirical_error_rate",
    "effective_error_rate",
    "repetition_factor",
    "toffoli_count",
    "num_qubits",
)


def seed_row(rows_path: Path, seed: int) -> dict[str, Any]:
    """One seed's three task costs, plus the dqi fields that explain its own variance."""
    rows = VerificationRun.read_rows(rows_path)
    missing = [t for t in TASKS if t not in rows]
    if missing:
        raise typer.BadParameter(f"{rows_path.name} is missing {', '.join(missing)}")
    failed = [t for t in TASKS if rows[t]["status"] != "PASS"]
    if failed:
        raise typer.BadParameter(f"{rows_path.name} did not pass {', '.join(failed)}")
    detail = rows["dqi"]["detail"]
    return {
        "seed": seed,
        "costs": {t: rows[t]["score"] for t in TASKS},
        "minutes": round(sum(rows[t]["seconds"] for t in TASKS) / 60, 2),
        "dqi_detail": {k: detail[k] for k in DQI_DETAIL if k in detail},
    }


def main(
    rows_dir: Annotated[Path, typer.Argument(help="directory of rows_seed_<n>.jsonl files")],
    submission_ref: Annotated[str, typer.Option(help="the Kaggle submission these re-verify")],
    shots_per_run: Annotated[int, typer.Option(help="the dqi verifier's shot budget per run")],
    measured_on: Annotated[str, typer.Option(help="ISO date the seeds were run")] = "",
) -> None:
    paths = sorted(rows_dir.glob("rows_seed_*.jsonl"), key=lambda p: int(p.stem.split("_")[-1]))
    if not paths:
        raise typer.BadParameter(f"no rows_seed_*.jsonl under {rows_dir}")
    record = {
        "submission": submission_ref,
        "measured_on": measured_on,
        "shots_per_run": shots_per_run,
        "seeds": [seed_row(p, int(p.stem.split("_")[-1])) for p in paths],
    }
    out = EXPERIMENTS_DIR / f"{submission_ref}-seeds.yaml"
    out.write_text(HEADER + yaml.safe_dump(record, sort_keys=False, default_flow_style=False))
    print(f"wrote {out} ({len(record['seeds'])} seeds)")


if __name__ == "__main__":
    typer.run(main)
