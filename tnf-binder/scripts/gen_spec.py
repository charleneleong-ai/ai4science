"""Emit BoltzGen design specs with chain-position indices derived from the structure.

BoltzGen's parse_range is 1-based *within the chain as stored in the file*, not by residue
number. 1TNF starts at residue 6, so writing mature numbers directly shifts the epitope by five.
`StoredNumbering` converts mature numbering -> chain position and asserts the residues it lands
on spell what they should.
"""

from __future__ import annotations

from pathlib import Path

import typer
from rich.console import Console
from rich.table import Table

from tnf_binder.specs import StoredNumbering

app = typer.Typer(add_completion=False)
console = Console()

LENGTHS = (65, 75, 85, 95)
ANTI_LENGTHS = (75, 85)

# Mature-numbering hotspots: the conserved lobe of the TNFR2 site, with the identities the
# target file must show at those numbers.
HOT: dict[str, tuple[tuple[int, ...], str]] = {
    "A": ((86, 87, 88, 90, 91, 92), "SYQKVN"),
    "B": ((33, 147), "AS"),
}
# Divergent human/mouse positions to steer away from.
ANTI: dict[str, tuple[int, ...]] = {"A": (85, 89), "B": (31,)}


def spec_text(target: str, hot: dict[str, str], anti: dict[str, str] | None,
              length: int) -> str:
    """One BoltzGen spec: the target's binding ranges, plus a designed chain of `length`."""
    binding = "\n".join(f'        - chain: {{id: {c}, binding: "{r}"}}'
                        for c, r in hot.items())
    coldspots = "" if anti is None else "\n" + "\n".join(
        f'        - chain: {{id: {c}, not_binding: "{r}"}}' for c, r in anti.items())
    return f"""# TNF-alpha conditional binder -- Adaptyv x Anthropic challenge 02.
#
# Epitope: the species-conserved lobe of the TNFR2 receptor site, computed from 3ALQ contacts
# intersected with the human/mouse alignment -- 90% conserved (685 vs 72 A^2 SASA), carrying
# conserved K90 as the anchor for the pH-release switch.
#
# Indices are 1-based CHAIN POSITIONS, not mature residue numbers: 1TNF starts at residue 6,
# so mature 86-92 is positions {hot['A']}. Generated by gen_spec.py -- do not hand-edit.
#
# No total_len constraint: BoltzGen compares it against target+binder and spins forever on a
# binder-only range. Length is set by the designed-sequence field below.
# msa: empty -- the target structure is given, so no MSA server round-trip is needed.
entities:
  - file:
      path: {target}
      msa: empty
      include:
        - chain: {{id: A}}
        - chain: {{id: B}}
      binding_types:
{binding}{coldspots}
  - protein:
      id: X
      sequence: "{length}"
      msa: empty
"""


@app.command()
def main(
    structure: Path = typer.Argument(..., help="the two-protomer target PDB (tnf_AB.pdb)"),
    out_dir: Path = typer.Argument(..., help="directory to write the specs into"),
    target: str = typer.Option("/home/ubuntu/tnf/targets/tnf_AB.pdb", "--target",
                               help="the target path BoltzGen will read on the design box"),
) -> None:
    """Write the length series, with and without the divergent-position coldspots."""
    numbering = StoredNumbering.from_file(structure)
    hot = {chain: numbering.ranges(chain, nums, expect)
           for chain, (nums, expect) in HOT.items()}
    anti = {chain: numbering.ranges(chain, nums) for chain, nums in ANTI.items()}

    table = Table(title="mature -> chain position · the off-by-five guard")
    for column in ("chain", "mature", "positions", "identities"):
        table.add_column(column)
    for chain, (nums, expect) in HOT.items():
        table.add_row(chain, str(list(nums)), hot[chain],
                      f"[green]{expect}[/]")  # ranges() raised already if it did not match
    console.print(table)
    console.print(f"coldspot ranges (chain positions): {anti}")

    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for length in LENGTHS:
        path = out_dir / f"tnf_a91_L{length}.yaml"
        path.write_text(spec_text(target, hot, None, length))
        written.append(path.name)
    for length in ANTI_LENGTHS:
        path = out_dir / f"tnf_a91_anti_L{length}.yaml"
        path.write_text(spec_text(target, hot, anti, length))
        written.append(path.name)
    console.print(f"wrote [bold]{len(written)}[/] specs into [cyan]{out_dir}[/]: {written}")


if __name__ == "__main__":
    app()
