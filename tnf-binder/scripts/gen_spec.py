"""Emit a BoltzGen design spec with chain-position indices derived from the structure.

BoltzGen's parse_range is 1-based *within the chain as stored in the file*, not by residue
number. 1TNF starts at residue 6, so writing mature numbers directly shifts the epitope by 5.
This converts mature numbering -> chain position and asserts the resulting sequence matches.
"""
import sys
from pathlib import Path
from Bio import PDB
from Bio.PDB.Polypeptide import protein_letters_3to1 as THREE2ONE

SD, OUTDIR = Path(sys.argv[1]), Path(sys.argv[2])
LENGTHS = [65, 75, 85, 95]
TARGET = "/home/ubuntu/tnf/targets/tnf_AB.pdb"

# Mature-numbering hotspots: the conserved lobe of the TNFR2 site.
HOT = {"A": [86, 87, 88, 90, 91, 92], "B": [33, 147]}
EXPECT = {"A": "SYQKVN", "B": "AS"}          # sanity: identities at those positions
# Divergent human/mouse positions to steer away from (anti-hotspots).
ANTI = {"A": [85, 89], "B": [31]}

st = PDB.PDBParser(QUIET=True).get_structure("t", SD / "tnf_AB.pdb")[0]

pos_of, aa_of = {}, {}
for ch in st:
    for i, res in enumerate((r for r in ch if r.id[0] == " "), start=1):
        pos_of[(ch.id, res.id[1])] = i
        aa_of[(ch.id, res.id[1])] = THREE2ONE.get(res.get_resname(), "X")

print("mature -> chain-position mapping (the off-by-five guard):")
for ch, nums in HOT.items():
    got = "".join(aa_of[(ch, n)] for n in nums)
    pos = [pos_of[(ch, n)] for n in nums]
    print(f"  chain {ch}: resnums {nums}")
    print(f"             positions {pos}")
    print(f"             identities {got!r}  expected {EXPECT[ch]!r}  {'OK' if got == EXPECT[ch] else 'MISMATCH'}")
    assert got == EXPECT[ch], f"hotspot identity mismatch on chain {ch}: {got} != {EXPECT[ch]}"

def ranges(nums: list[int]) -> str:
    """Collapse sorted ints into BoltzGen 'a..b,c' range syntax."""
    nums, out, i = sorted(nums), [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(f"{nums[i]}..{nums[j]}" if j > i else f"{nums[i]}")
        i = j + 1
    return ",".join(out)

hot_r = {ch: ranges([pos_of[(ch, n)] for n in nums]) for ch, nums in HOT.items()}
anti_r = {ch: ranges([pos_of[(ch, n)] for n in nums]) for ch, nums in ANTI.items()}
print(f"\nbinding ranges (chain positions): {hot_r}")
print(f"anti  ranges (chain positions): {anti_r}")

OUTDIR.mkdir(parents=True, exist_ok=True)

def spec_text(length: int, use_anti: bool) -> str:
    anti = ""
    if use_anti:
        anti = (f'\n        - chain: {{id: A, not_binding: "{anti_r["A"]}"}}'
                f'\n        - chain: {{id: B, not_binding: "{anti_r["B"]}"}}')
    return f"""# TNF-alpha conditional binder -- Adaptyv x Anthropic challenge 02.
#
# Epitope: the species-conserved lobe of the TNFR2 receptor site, computed from 3ALQ contacts
# intersected with the human/mouse alignment -- 90% conserved (685 vs 72 A^2 SASA), carrying
# conserved K90 as the anchor for the pH-release switch.
#
# Indices are 1-based CHAIN POSITIONS, not mature residue numbers: 1TNF starts at residue 6,
# so mature 86-92 is positions {hot_r['A']}. Generated by gen_spec.py -- do not hand-edit.
#
# No total_len constraint: BoltzGen compares it against target+binder and spins forever on a
# binder-only range. Length is set by the designed-sequence field below.
# msa: empty -- the target structure is given, so no MSA server round-trip is needed.
entities:
  - file:
      path: {TARGET}
      msa: empty
      include:
        - chain: {{id: A}}
        - chain: {{id: B}}
      binding_types:
        - chain: {{id: A, binding: "{hot_r['A']}"}}
        - chain: {{id: B, binding: "{hot_r['B']}"}}{anti}
  - protein:
      id: X
      sequence: "{length}"
      msa: empty
"""

written = []
for L in LENGTHS:
    f = OUTDIR / f"tnf_a91_L{L}.yaml"
    f.write_text(spec_text(L, use_anti=False)); written.append(f.name)
for L in (75, 85):
    f = OUTDIR / f"tnf_a91_anti_L{L}.yaml"
    f.write_text(spec_text(L, use_anti=True)); written.append(f.name)

print(f"\nwrote {len(written)} specs into {OUTDIR}: {written}")
print("\n--- sample (tnf_a91_anti_L75.yaml) ---")
print((OUTDIR / "tnf_a91_anti_L75.yaml").read_text())
