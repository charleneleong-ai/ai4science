"""Emitting BoltzGen specs, with every index checked against the structure it refers to.

    gen.py spec   targets/tnf_AB.pdb     specs/boltzgen/
    gen.py screen targets/tnf_trimer.pdb specs/screen/

Two commands because the YAML is genuinely different -- `spec` writes a length series against two
protomers with coldspots on the divergent positions, `screen` writes one spec per config against
the trimer with a secondary-structure bias and no coldspots -- and collapsing them into one
parameterised builder needed six optional arguments to say less. What they do share is the part
that went wrong.

The shared hazard, stated once: BoltzGen's `parse_range` is 1-based *within the chain as stored
in the file*, not by residue number. 1TNF starts at residue 6, so writing mature numbers
straight into a spec shifts the epitope by five residues and the run still completes, having
designed against the wrong surface. `StoredNumbering` converts mature numbering to chain
position and asserts that the positions it lands on spell the residues they should, so a shift
fails loudly at spec-writing time instead of quietly after a day of GPU.
"""

from __future__ import annotations

from pathlib import Path

import typer
from rich.console import Console
from rich.table import Table

from tnf_binder.specs import StoredNumbering, secondary_structure

app = typer.Typer(add_completion=False)
console = Console()

# chain -> (mature residue numbers, the residues the target file must show at them)
Sites = dict[str, tuple[tuple[int, ...], str]]

OUT_DIR = typer.Argument(..., help="directory to write the specs into")

LENGTHS = (65, 75, 85, 95)
ANTI_LENGTHS = (75, 85)

# Mature-numbering hotspots: the conserved lobe of the TNFR2 site, with the identities the
# target file must show at those numbers.
HOT: Sites = {
    "A": ((86, 87, 88, 90, 91, 92), "SYQKVN"),
    "B": ((33, 147), "AS"),
}
# Divergent human/mouse positions to steer away from.
ANTI: dict[str, tuple[int, ...]] = {"A": (85, 89), "B": (31,)}

# Candidate epitopes for the screen, mature numbering, with their expected identities.
EPITOPES: Sites = {
    # concave hydrophobic conserved pocket -- the designability winner
    "pocket": ((113, 115, 143, 144), "PYLF"),
    # the original lobe, narrowed from 8 spread residues to 3 tight ones
    "lobe3": ((88, 90, 92), "QKN"),
    # pocket plus two more conserved contacts, still one protomer
    "pocket5": ((67, 113, 115, 143, 144), "QPYLF"),
}

# name, epitope, length range, helix-biased
CONFIGS: tuple[tuple[str, str, str, bool], ...] = (
    ("pocket_free", "pocket", "60..95", False),
    ("pocket_helix", "pocket", "60..95", True),
    ("pocket5_helix", "pocket5", "70..110", True),
    ("lobe3_free", "lobe3", "60..95", False),
)


def chain_ranges(numbering: StoredNumbering, sites: Sites) -> dict[str, str]:
    """Mature numbering -> chain-position ranges, each asserted against its residue identities."""
    return {chain: numbering.ranges(chain, nums, expect)
            for chain, (nums, expect) in sites.items()}


def spec_text(target: str, hot: dict[str, str], anti: dict[str, str] | None,
              length: int) -> str:
    """One design spec: the target's binding ranges, plus a designed chain of `length`."""
    binding = "\n".join(f'        - chain: {{id: {c}, binding: "{r}"}}'
                        for c, r in hot.items())
    coldspots = "" if anti is None else "\n" + "\n".join(
        f'        - chain: {{id: {c}, not_binding: "{r}"}}' for c, r in anti.items())
    return f"""# TNF-alpha conditional binder -- Adaptyv x Anthropic challenge 02.
#
# Epitope: the species-conserved lobe of the TNFR2 receptor site, computed from 3ALQ contacts
# intersected with the human/mouse alignment -- 90% conserved (685 vs 72 A^2 SASA), carrying
# conserved K90 as the anchor for the pH-release switch.
#
# Indices are 1-based CHAIN POSITIONS, not mature residue numbers: 1TNF starts at residue 6,
# so mature 86-92 is positions {hot['A']}. Generated by gen.py -- do not hand-edit.
#
# No total_len constraint: BoltzGen compares it against target+binder and spins forever on a
# binder-only range. Length is set by the designed-sequence field below.
# msa: empty -- the target structure is given, so no MSA server round-trip is needed.
entities:
  - file:
      path: {target}
      msa: empty
      include:
        - chain: {{id: A}}
        - chain: {{id: B}}
      binding_types:
{binding}{coldspots}
  - protein:
      id: X
      sequence: "{length}"
      msa: empty
"""


def screen_text(name: str, target: str, epitope: str, binding: str, length_range: str,
                pattern: str | None) -> str:
    ss_line = "" if pattern is None else f'\n      secondary_structure: "{pattern}"'
    ss_desc = "unconstrained" if pattern is None else f"3-helix bundle over {len(pattern)} residues"
    return f"""# TNF-alpha binder screen config: {name}
# epitope={epitope}  length={length_range}  secondary_structure={ss_desc}
#
# Screening to lift design_to_target_iptm off the 0.11-0.30 plateau. Indices are 1-based CHAIN
# POSITIONS; target files keep 1TNF numbering so position = mature - 5, asserted by gen.py.
entities:
  - protein:
      id: X
      sequence: {length_range}{ss_line}
  - file:
      path: {target}
      include:
        - chain: {{id: A}}
        - chain: {{id: B}}
        - chain: {{id: C}}
      binding_types:
        - chain: {{id: A, binding: "{binding}"}}
      structure_groups: "all"
"""


@app.command()
def spec(
    structure: Path = typer.Argument(..., help="the two-protomer target PDB (tnf_AB.pdb)"),
    out_dir: Path = OUT_DIR,
    target: str = typer.Option("/home/ubuntu/tnf/targets/tnf_AB.pdb", "--target",
                               help="the target path BoltzGen will read on the design box"),
) -> None:
    """Write the length series, with and without the divergent-position coldspots."""
    numbering = StoredNumbering.from_file(structure)
    hot = chain_ranges(numbering, HOT)
    anti = {chain: numbering.ranges(chain, nums) for chain, nums in ANTI.items()}

    table = Table(title="mature -> chain position · the off-by-five guard")
    for column in ("chain", "mature", "positions", "identities"):
        table.add_column(column)
    for chain, (nums, expect) in HOT.items():
        table.add_row(chain, str(list(nums)), hot[chain],
                      f"[green]{expect}[/]")  # ranges() raised already if it did not match
    console.print(table)
    console.print(f"coldspot ranges (chain positions): {anti}")

    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for length in LENGTHS:
        path = out_dir / f"tnf_a91_L{length}.yaml"
        path.write_text(spec_text(target, hot, None, length))
        written.append(path.name)
    for length in ANTI_LENGTHS:
        path = out_dir / f"tnf_a91_anti_L{length}.yaml"
        path.write_text(spec_text(target, hot, anti, length))
        written.append(path.name)
    console.print(f"wrote [bold]{len(written)}[/] specs into [cyan]{out_dir}[/]: {written}")


@app.command()
def screen(
    structure: Path = typer.Argument(..., help="the trimer target PDB (tnf_trimer.pdb)"),
    out_dir: Path = OUT_DIR,
    target: str = typer.Option("/home/ubuntu/tnf/targets/tnf_trimer.pdb", "--target",
                               help="the target path BoltzGen will read on the design box"),
) -> None:
    """Write one spec per screen config, each with its numbering asserted.

    The levers, in expected order of impact: the epitope (the original hotspots spanned 8
    residues, two protomers and 18 A -- far more than the 3-5 tight hotspots that are standard
    practice, and centred on the LEAST designable conserved cluster), a helix bias (all-helical
    binders are markedly easier to design and re-predict confidently), then length. Every
    architecture so far plateaued at design_to_target_iptm 0.11-0.30 against a ~0.5 bar, so the
    point is to screen the untested levers cheaply rather than scale a config that does not work.
    """
    numbering = StoredNumbering.from_file(structure)
    out_dir.mkdir(parents=True, exist_ok=True)

    for name, epitope, length_range, helix in CONFIGS:
        positions, expect = EPITOPES[epitope]
        binding = numbering.ranges("A", positions, expect)
        pattern = secondary_structure(length_range) if helix else None
        console.print(f"[bold]{name}[/] epitope={epitope} mature={list(positions)} -> "
                      f"positions {binding} ({expect}) length={length_range} "
                      f"ss={'bundle' if helix else 'free'}")
        (out_dir / f"screen_{name}.yaml").write_text(
            screen_text(name, target, epitope, binding, length_range, pattern))

    console.print(f"wrote [bold]{len(CONFIGS)}[/] screen specs to [cyan]{out_dir}[/]")


if __name__ == "__main__":
    app()
